/* Actual browser integration checks and captioned demo. Requires a fresh demo DB. */
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const out = path.join(root, 'artifacts');
const evidence = path.join(out, 'evidence');
const base = process.env.DEMO_URL || 'http://127.0.0.1:8766';

(async () => {
  fs.mkdirSync(evidence, {recursive: true});
  const browser = await chromium.launch({headless: true, ...(process.env.BROWSER_CHANNEL ? {channel: process.env.BROWSER_CHANNEL} : {})});
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, recordVideo: {dir: path.join(out, 'raw-video'), size: {width: 1440, height: 1000}}});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  assert.equal((await (await context.request.get(base + '/api/state')).json()).records.length, 0, 'Use a fresh demo database');
  await page.evaluate(() => {const banner=document.createElement('div');banner.id='demo-caption';Object.assign(banner.style,{position:'fixed',bottom:'0',left:'0',right:'0',background:'#112c3a',color:'white',padding:'17px 35px',font:'600 20px Segoe UI',textAlign:'center',zIndex:'10000',borderTop:'3px solid #19baa7'});document.body.appendChild(banner);document.body.style.paddingBottom='85px'});
  const caption = async text => {await page.locator('#demo-caption').evaluate((el,t)=>el.textContent=t,text);console.log(text)};
  const pause = ms => page.waitForTimeout(ms);
  const state = async id => (await (await context.request.get(base+'/api/runs/'+id)).json());
  async function run(example, expected='completed') {
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.locator(`[data-example="${example}"]`).click();
    const response = page.waitForResponse(r=>r.url()===base+'/api/runs' && r.request().method()==='POST');
    await page.locator('#run').click();
    const run = await (await response).json();
    await page.waitForFunction(async ({id,status}) => {const r=await (await fetch('/api/runs/'+id)).json();return r.status===status},{id:run.id,status:expected});
    await page.waitForTimeout(1000);
    return state(run.id);
  }
  await caption('LedgerLens: an outcome-based financial research worker. Fictional data; real execution.');
  await pause(6000);
  await caption('1 / Missing source → choose an approved alternative → calculate → save → verify.');
  let aurora=await run('aurora');
  assert.equal(aurora.candidate.revenue,'1250.00');
  assert.equal(aurora.verification.database_readback_match,true);
  assert(aurora.events.some(e=>!e.ok && e.tool==='read_report'));
  await page.screenshot({path:path.join(out,'dashboard.png'),fullPage:true});
  fs.writeFileSync(path.join(evidence,'aurora-recovery.json'),JSON.stringify(aurora,null,2));
  await pause(6500);
  await page.locator('.event').filter({hasText:'FileNotFoundError'}).scrollIntoViewIfNeeded();
  await pause(5000);
  await page.locator('#records').scrollIntoViewIfNeeded();
  await caption('Aurora: revenue 1,250m; net profit 150m; margin 12%; growth 25%. Saved values checked.');
  await pause(6500);
  await caption('2 / Repeat the same task. The existing identical record is reused, not duplicated.');
  const rerun=await run('aurora');
  assert(rerun.events.some(e=>e.tool==='save_record' && e.observation.outcome==='already present'));
  assert.equal((await (await context.request.get(base+'/api/state')).json()).records.length,1);
  fs.writeFileSync(path.join(evidence,'aurora-idempotent.json'),JSON.stringify(rerun,null,2));
  await pause(6000);
  await caption('3 / Beacon reports disagree: 800m versus 810m revenue. The worker stops for review.');
  let beacon=await run('beacon','awaiting_approval');
  await page.locator('#approval').scrollIntoViewIfNeeded();
  assert.equal((await (await context.request.get(base+'/api/state')).json()).records.length,1);
  await page.screenshot({path:path.join(out,'approval.png'),fullPage:true});
  await pause(6500);
  await page.locator('#source').selectOption('beacon_2026.html');
  await page.locator('#reason').fill('Reviewed the sandbox primary annual report; use its 800 million revenue.');
  await caption('A human selects the observed source and explains the decision. The audit retains it.');
  await pause(4500);
  await page.locator('#approve').click();
  await page.waitForFunction(async id=>(await (await fetch('/api/runs/'+id)).json()).status==='completed',beacon.id);
  await pause(1000);
  beacon=await state(beacon.id);
  assert.equal(beacon.approvals.length,1);
  assert.equal(beacon.candidate.revenue,'800.00');
  fs.writeFileSync(path.join(evidence,'beacon-approved.json'),JSON.stringify(beacon,null,2));
  await page.evaluate(()=>window.scrollTo(0,0));
  await caption('The worker resumes, writes the approved result, and verifies it independently.');
  await pause(6000);
  await caption('4 / Read-only analysis: Cedar has growing sales and a loss. No record should be written.');
  const cedar=await run('cedar');
  assert.equal(cedar.candidate.net_profit,'-25.00');
  assert.equal(cedar.verification.database_readback_match,null);
  assert.equal((await (await context.request.get(base+'/api/state')).json()).records.length,2);
  fs.writeFileSync(path.join(evidence,'cedar-readonly.json'),JSON.stringify(cedar,null,2));
  await pause(8000);
  await caption('5 / Missing company: ask for clarification. The worker does not guess or write data.');
  const missing=await run('unknown','needs_input');
  assert.equal(missing.status,'needs_input');
  fs.writeFileSync(path.join(evidence,'clarification.json'),JSON.stringify(missing,null,2));
  await pause(7000);
  await caption('Bounded rule-based autonomy. No LLM call in this demo. Full source, tests and limitations included.');
  await page.locator(`[data-run="${aurora.id}"]`).click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await pause(6000);
  assert.deepEqual(errors,[]);
  const video=page.video();
  await context.close();
  await video.saveAs(path.join(out,'demo.webm'));
  await browser.close();
  fs.writeFileSync(path.join(evidence,'browser-checks.json'),JSON.stringify({passed:true,checked_at:new Date().toISOString(),scenarios:['missing source recovery and verified write','idempotent repeat','conflict blocks write until approval','approval resumes and verifies','read-only loss and unit conversion','clarification without guessing'],page_errors:errors,real_model_run:false},null,2));
  console.log('PASS: recorded actual browser demo and six UI scenarios');
})().catch(error=>{console.error(error);process.exit(1)});
